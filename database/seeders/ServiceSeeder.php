/**
 * Service pages.
 *
 * Phase 1 publishes the four pillar pages with complete, original copy. The
 * remaining services are seeded as drafts carrying only their title, slug and
 * category — a draft is invisible to the public and excluded from the
 * sitemap, so the site never ships a thin or duplicated page. Phase 2 fills
 * their copy.
 *
 * Every published page here is marked needs_review: the wording is drafted
 * from the supplied service scope and must be read by the lawyer before it
 * goes live. That flag is admin-only and never rendered publicly.
 *
 * Licence keys are attached only where the licence is genuinely relevant to
 * the service described.
 */
class ServiceSeeder extends Seeder
{
    public function run(): void
    {
        $categories = ServiceCategory::query()->pluck('id', 'slug');

        foreach ($this->publishedServices() as $service) {
            $categorySlug = $service['category'];
            unset($service['category']);

            Service::updateOrCreate(
                ['slug' => $service['slug']],
                [...$service, 'service_category_id' => $categories[$categorySlug]],
            );
        }

        foreach ($this->draftServices() as $position => $draft) {
            Service::updateOrCreate(
                ['slug' => $draft['slug']],
                [
                    'service_category_id' => $categories[$draft['category']],
                    'title' => $draft['title'],
                    'h1' => $draft['title'],
                    'status' => Service::STATUS_DRAFT,
                    'needs_review' => true,
                    'position' => $position + 10,
                ],
            );
        }
    }

