    public function run(): void
    {
        $categories = $this->seedCategories();
        $authorName = User::query()->where('is_admin', true)->value('name');

        foreach ($this->postsData() as $data) {
            $categorySlug = $data['category_slug'];
            $serviceSlug = $data['service_slug'] ?? null;
            $focusPhrase = $data['focus_phrase'] ?? null;

            unset($data['category_slug'], $data['service_slug'], $data['focus_phrase']);

            $categoryId = $categories[$categorySlug] ?? null;

            /** @var Post $post */
            $post = Post::query()->updateOrCreate(
                ['slug' => $data['slug']],
                [
                    'post_category_id' => $categoryId,
                    'title' => $data['title'],
                    'h1' => $data['title'],
                    'excerpt' => $data['excerpt'],
                    'body' => $data['body'],
                    'seo_title' => $data['seo_title'],
                    'seo_description' => $data['seo_description'],
                    'focus_phrase' => $focusPhrase,
                    'status' => 'draft',
                    'published_at' => null,
                    'needs_review' => true,
                    'author_name' => $authorName,
                ]
            );

            $post->reading_minutes = $post->calculateReadingMinutes();
            $post->save();

            if ($serviceSlug) {
                $service = Service::query()->where('slug', $serviceSlug)->first();
                if ($service) {
                    $post->services()->sync([$service->id => ['position' => 1]]);
                }
            }
        }
    }

